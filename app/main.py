import json
from pathlib import Path

from flask import Flask, abort, redirect, render_template, request, url_for

# Static files live in public/ so Vercel's CDN serves them; Flask serves the
# same folder at /static when running locally.
app = Flask(__name__, static_folder="../public/static", static_url_path="/static")

CURRENT_YEAR = 2027
YEARS = [2027, 2026, 2025, 2024]
POSITIONS = ["QB", "RB", "WR", "TE", "OT", "IOL", "IDL", "EDGE", "LB", "CB", "SAF"]

# Each draft year has its own color theme (defined in public/static/style.css).
YEAR_THEMES = {
    2027: "broadcast",
    2026: "turf",
    2025: "ultraviolet",
    2024: "midnight",
}

# ---------------------------------------------------------------- data
# app/data/<year>.json is generated by scripts/import_data.py from the
# Excel workbooks and Word scouting reports.
DATA_DIR = Path(__file__).parent / "data"


def load_year(year):
    path = DATA_DIR / f"{year}.json"
    if not path.exists():
        return None
    data = json.loads(path.read_text(encoding="utf-8"))
    data["by_slug"] = {p["slug"]: p for p in data["players"]}
    # Tier number (1 = best) drives the tier color ramp in style.css
    tier_num = {name: i for i, name in enumerate(data["tiers"], start=1)}
    for item in data["players"] + data["big_board"]:
        item["tier_num"] = tier_num.get(item.get("tier"))
    # Big board grouped by tier, in board order
    tiers = []
    for tier in data["tiers"]:
        entries = [e for e in data["big_board"] if e["tier"] == tier]
        if entries:
            tiers.append({"name": tier, "num": tier_num[tier], "entries": entries})
    data["board_by_tier"] = tiers
    # Grade range of the class, for the grade meters (each year uses its own scale)
    grades = [g for g in (p.get("grade") for p in data["players"]) if g is not None]
    data["grade_range"] = (min(grades), max(grades)) if grades else (0, 1)
    return data


DATA = {year: load_year(year) for year in YEARS}

# Post-draft value: app/data/<year>_value.json, generated by scripts/post_draft_value.py
VALUE_ROOMS = ["QB", "RB", "WR", "TE", "EDGE", "IDL", "LB", "CB", "S"]


def load_value(year):
    path = DATA_DIR / f"{year}_value.json"
    if not path.exists():
        return None
    data = json.loads(path.read_text(encoding="utf-8"))
    for p in data["players"] + data["not_graded"]:
        # Current team: the most recent season he was on a team
        seasons = [s for s in p.get("seasons", []) if s.get("team")]
        p["current_team"] = seasons[-1]["team"] if seasons else None
    data["rooms"] = [r for r in VALUE_ROOMS if any(p["room"] == r for p in data["players"])]
    return data


VALUE = {year: load_value(year) for year in YEARS}


def year_data(year):
    if year not in YEARS:
        abort(404)
    return DATA.get(year)


@app.template_filter("grade")
def format_grade(value, places=2):
    if value is None:
        return "—"
    return f"{value:.{places}f}"


def grade_position(year, value):
    """Where a grade sits within that year's class, as a 0-100 percentage."""
    data = DATA.get(year)
    if not data or value is None:
        return None
    lo, hi = data["grade_range"]
    if hi <= lo:
        return 50
    return round(max(0.0, min(1.0, (value - lo) / (hi - lo))) * 100, 1)


# A global (not just context) so imported macros in _macros.html can use it.
app.jinja_env.globals["grade_position"] = grade_position


@app.context_processor
def inject_site_data():
    return {"years": YEARS, "current_year": CURRENT_YEAR, "year_themes": YEAR_THEMES}


# ---------------------------------------------------------------- routes

# The per-year dropdown menu: (view function name, label)
SECTIONS = [
    ("watch_list", "Watch List"),
    ("big_board", "Big Board"),
    ("rankings", "Rankings"),
    ("reports", "Scouting Reports"),
    ("post_draft", "Post-Draft Analysis"),
]
app.jinja_env.globals["sections"] = SECTIONS


# Watch list: a consensus of public big boards (app/data/<year>_watchlist.json), used to pick which
# players to watch before the year's own rankings exist. Only years that have one show it in the menu.
def load_watchlist(year):
    path = DATA_DIR / f"{year}_watchlist.json"
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else None


WATCHLISTS = {year: load_watchlist(year) for year in YEARS}
app.jinja_env.globals["watchlist_years"] = {y for y, w in WATCHLISTS.items() if w}

OPTIONAL_COLUMNS = ["size_score", "athleticism", "tape_grade"]


def available_columns(players):
    """Optional stat columns that have data this year (2026 sheets don't track them)."""
    return {c for c in OPTIONAL_COLUMNS if any(p.get(c) is not None for p in players)}


def players_by_position(data, with_reports_only=False):
    groups = {}
    for pos in POSITIONS:
        group = [p for p in (data["players"] if data else []) if p.get("group") == pos]
        if with_reports_only:
            group = [p for p in group if p.get("reports")]
        groups[pos] = sorted(group, key=lambda p: p.get("position_rank") or 999)
    return groups


@app.route("/")
def index():
    return big_board(CURRENT_YEAR)


@app.route("/<int:year>")
@app.route("/<int:year>/big-board")
def big_board(year):
    data = year_data(year)
    return render_template("big_board.html", year=year, section="big_board", data=data)


@app.route("/<int:year>/watch-list")
def watch_list(year):
    if year not in YEARS:
        abort(404)
    wl = WATCHLISTS.get(year)
    if not wl:
        abort(404)
    view = (request.args.get("pos") or "ALL").upper()
    if view != "ALL" and view not in wl["positions"]:
        view = "ALL"
    rows = wl["board"] if view == "ALL" else wl["positions"][view]
    return render_template("watch_list.html", year=year, section="watch_list", wl=wl, view=view, rows=rows,
                           positions=list(wl["positions"]))


@app.route("/<int:year>/rankings")
def rankings(year):
    data = year_data(year)
    return render_template(
        "rankings.html", year=year, section="rankings", data=data,
        positions=POSITIONS, groups=players_by_position(data),
    )


@app.route("/<int:year>/rankings/<pos>")
def position_page(year, pos):
    data = year_data(year)
    pos = pos.upper()
    if not data or pos not in POSITIONS:
        abort(404)
    return render_template(
        "position.html", year=year, section="rankings", pos=pos, positions=POSITIONS,
        players=players_by_position(data)[pos], cols=available_columns(data["players"]),
    )


@app.route("/<int:year>/<pos>")
def old_position_url(year, pos):
    # Position pages used to live at /<year>/<POS>
    if pos.upper() not in POSITIONS:
        abort(404)
    return redirect(url_for("position_page", year=year, pos=pos.upper()), code=301)


@app.route("/<int:year>/reports")
def reports(year):
    data = year_data(year)
    groups = players_by_position(data, with_reports_only=True)
    return render_template(
        "reports.html", year=year, section="reports", data=data, groups=groups,
        report_count=sum(len(g) for g in groups.values()),
    )


@app.route("/<int:year>/post-draft")
def post_draft(year):
    year_data(year)  # 404 for unknown years
    value = VALUE.get(year)
    view = request.args.get("pos", "QB").upper()
    if value:
        valid = value["rooms"] + ["OL", "ALL", "DRAFT"]
        if view not in valid:
            view = valid[0]
        if view == "DRAFT":
            # Every pick in order (offensive linemen included), then undrafted players from your board
            everyone = value["players"] + value["not_graded"]
            rows = sorted((p for p in everyone if p.get("pick")), key=lambda p: p["pick"])
            rows += sorted((p for p in everyone if not p.get("pick")), key=lambda p: p.get("board_rank") or 999)
        elif view == "ALL":
            rows = value["players"]
        elif view == "OL":
            rows = sorted(value["not_graded"], key=lambda p: p.get("pick") or 999)
        else:
            rows = [p for p in value["players"] if p["room"] == view]
    else:
        rows = []
    return render_template("post_draft.html", year=year, section="post_draft",
                           value=value, view=view, rows=rows)


@app.route("/<int:year>/player/<slug>")
def player_page(year, slug):
    data = year_data(year)
    if not data or slug not in data["by_slug"]:
        abort(404)
    player = data["by_slug"][slug]
    return render_template(
        "player.html", year=year, section="reports", player=player,
        cols=available_columns(data["players"]),
    )


@app.route("/about")
def about():
    return render_template("about.html", active="about")
