import json
from pathlib import Path

from flask import Flask, abort, render_template

# Static files live in public/ so Vercel's CDN serves them; Flask serves the
# same folder at /static when running locally.
app = Flask(__name__, static_folder="../public/static", static_url_path="/static")

CURRENT_YEAR = 2027
YEARS = [2027, 2026, 2025, 2024]
POSITIONS = ["QB", "RB", "WR", "TE", "OT", "IOL", "IDL", "EDGE", "LB", "CB", "SAF"]

# Each draft year has its own color theme (defined in public/static/style.css).
YEAR_THEMES = {
    2027: "broadcast",
    2026: "turf",
    2025: "ultraviolet",
    2024: "midnight",
}

# ---------------------------------------------------------------- data
# app/data/<year>.json is generated by scripts/import_data.py from the
# Excel workbooks and Word scouting reports.
DATA_DIR = Path(__file__).parent / "data"


def load_year(year):
    path = DATA_DIR / f"{year}.json"
    if not path.exists():
        return None
    data = json.loads(path.read_text(encoding="utf-8"))
    data["by_slug"] = {p["slug"]: p for p in data["players"]}
    # Big board grouped by tier, in board order
    tiers = []
    for tier in data["tiers"]:
        entries = [e for e in data["big_board"] if e["tier"] == tier]
        if entries:
            tiers.append({"name": tier, "entries": entries})
    data["board_by_tier"] = tiers
    return data


DATA = {year: load_year(year) for year in YEARS}


def year_data(year):
    if year not in YEARS:
        abort(404)
    return DATA.get(year)


@app.template_filter("grade")
def format_grade(value, places=2):
    if value is None:
        return "—"
    return f"{value:.{places}f}"


@app.context_processor
def inject_site_data():
    return {"years": YEARS, "current_year": CURRENT_YEAR, "year_themes": YEAR_THEMES}


# ---------------------------------------------------------------- routes

def render_year(year):
    data = year_data(year)
    position_counts = {}
    if data:
        for pos in POSITIONS:
            group = [p for p in data["players"] if p.get("group") == pos]
            position_counts[pos] = {
                "players": len(group),
                "reports": sum(1 for p in group if p.get("reports")),
            }
    return render_template(
        "index.html",
        year=year,
        data=data,
        positions=POSITIONS,
        position_counts=position_counts,
        player_count=len(data["players"]) if data else 0,
        report_count=sum(1 for p in data["players"] if p.get("reports")) if data else 0,
    )


@app.route("/")
def index():
    return render_year(CURRENT_YEAR)


@app.route("/<int:year>")
def year_page(year):
    return render_year(year)


@app.route("/<int:year>/<pos>")
def position_page(year, pos):
    data = year_data(year)
    pos = pos.upper()
    if not data or pos not in POSITIONS:
        abort(404)
    players = sorted(
        (p for p in data["players"] if p.get("group") == pos),
        key=lambda p: p.get("position_rank") or 999,
    )
    return render_template(
        "position.html", year=year, pos=pos, players=players, positions=POSITIONS,
        cols=available_columns(data["players"]),
    )


OPTIONAL_COLUMNS = ["size_score", "athleticism", "tape_grade"]


def available_columns(players):
    """Optional stat columns that have data this year (2026 sheets don't track them)."""
    return {c for c in OPTIONAL_COLUMNS if any(p.get(c) is not None for p in players)}


@app.route("/<int:year>/player/<slug>")
def player_page(year, slug):
    data = year_data(year)
    if not data or slug not in data["by_slug"]:
        abort(404)
    player = data["by_slug"][slug]
    return render_template("player.html", year=year, player=player, cols=available_columns(data["players"]))


@app.route("/about")
def about():
    return render_template("about.html", active="about")
